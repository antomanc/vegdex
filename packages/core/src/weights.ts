/** The table entry that weighs this ingredient: its pattern and grams per US cup. */
export function cupWeight(name: string): { pattern: string; grams: number } | null {
  const n = name.toLowerCase().trim();
  const hit = n ? CUP_GRAMS.find(([re]) => re.test(n)) : undefined;
  return hit ? { pattern: hit[0].source, grams: hit[1] } : null;
}

/** Grams in one US cup of this ingredient, or null when the table has no idea. */
export function gramsPerCup(name: string): number | null {
  return cupWeight(name)?.grams ?? null;
}
